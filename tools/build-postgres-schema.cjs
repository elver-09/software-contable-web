"use strict";
const fs = require("node:fs");
const path = require("node:path");
const source = require("../server/postgres/schema-original.json");
const tables = [
  ...new Map(
    [...source.empresa, ...source.global].map((t) => [t.name, t]),
  ).values(),
];
const shared = new Set(source.global.map((t) => t.name));
const ident = (s) => '"' + s.replaceAll('"', '""') + '"';
const now =
  "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'America/Lima', 'YYYY-MM-DD HH24:MI:SS')";
let sql = `-- Generated from the original desktop migrations. Review changes in this file before deployment.
-- Run through tools/apply-postgres-schema.cjs; requires a private PostgreSQL connection.
CREATE SCHEMA IF NOT EXISTS ansorito;
REVOKE ALL ON SCHEMA ansorito FROM PUBLIC;
GRANT USAGE ON SCHEMA ansorito TO authenticated;
CREATE TABLE ansorito.empresas (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id),
  nombre text NOT NULL CHECK (length(trim(nombre)) > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (owner_id, id)
);
ALTER TABLE ansorito.empresas ENABLE ROW LEVEL SECURITY;
ALTER TABLE ansorito.empresas FORCE ROW LEVEL SECURITY;
CREATE POLICY empresa_owner ON ansorito.empresas TO authenticated
  USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());
GRANT SELECT, INSERT, UPDATE, DELETE ON ansorito.empresas TO authenticated;
CREATE FUNCTION ansorito.current_scope() RETURNS uuid LANGUAGE sql STABLE
SET search_path = pg_catalog AS $$
  SELECT nullif(current_setting('ansorito.scope_id', true), '')::uuid
$$;
REVOKE ALL ON FUNCTION ansorito.current_scope() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION ansorito.current_scope() TO authenticated;
`;
for (const t of tables) {
  const pk = t.columns
    .filter((c) => c.pk)
    .sort((a, b) => a.pk - b.pk)
    .map((c) => c.name);
  const columns = t.columns.map((c) => {
    let type =
      c.type === "REAL" ? "numeric" : c.type === "INTEGER" ? "integer" : "text";
    if (c.name === "id" && /AUTOINCREMENT/i.test(t.sql)) {
      const firstId =
        Math.max(0, ...t.seed.map((row) => Number(row.id) || 0)) + 1;
      type += ` GENERATED BY DEFAULT AS IDENTITY (START WITH ${firstId})`;
    }
    let value = c.dflt_value;
    if (value && (/datetime\(/i.test(value) || value === "CURRENT_TIMESTAMP"))
      value = now;
    return `  ${ident(c.name)} ${type}${c.notnull || c.pk ? " NOT NULL" : ""}${value !== null ? " DEFAULT " + value : ""}`;
  });
  columns.unshift(
    "  owner_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id)",
    "  scope_id uuid NOT NULL DEFAULT ansorito.current_scope()",
  );
  columns.push(`  PRIMARY KEY (scope_id, ${pk.map(ident).join(", ")})`);
  for (const index of t.indexes.filter((i) => i.unique && i.origin === "u")) {
    columns.push(
      `  UNIQUE (scope_id, ${index.columns.map((c) => ident(c.name)).join(", ")})`,
    );
  }
  if (/CHECK \(id = 1\)/.test(t.sql)) columns.push("  CHECK (id = 1)");
  if (t.name === "comprobantes_tributarios")
    columns.push("  CHECK (tipo_registro IN ('VENTA','COMPRA'))");
  sql += `\nCREATE TABLE ansorito.${ident(t.name)} (\n${columns.join(",\n")}\n);\n`;
  const permitted = `${shared.has(t.name) ? "scope_id = auth.uid() OR " : ""}EXISTS (SELECT 1 FROM ansorito.empresas e WHERE e.id = scope_id AND e.owner_id = auth.uid())`;
  const predicate = `owner_id = auth.uid() AND scope_id = ansorito.current_scope() AND (${permitted})`;
  sql += `ALTER TABLE ansorito.${ident(t.name)} ENABLE ROW LEVEL SECURITY;
ALTER TABLE ansorito.${ident(t.name)} FORCE ROW LEVEL SECURITY;
CREATE POLICY isolated_scope ON ansorito.${ident(t.name)} TO authenticated
  USING (${predicate}) WITH CHECK (${predicate});
GRANT SELECT, INSERT, UPDATE, DELETE ON ansorito.${ident(t.name)} TO authenticated;
`;
}
// Desktop migrations lack these foreign keys. Add them to prevent orphan records.
for (const [table, column, target, targetColumn] of [
  ["voucher_detalles", "voucher_id", "vouchers", "id"],
  ["comprobantes_tributarios", "voucher_id", "vouchers", "id"],
  ["comprobante_venta", "comprobante_id", "comprobantes_tributarios", "id"],
  ["comprobante_compra", "comprobante_id", "comprobantes_tributarios", "id"],
])
  sql += `ALTER TABLE ansorito.${ident(table)} ADD FOREIGN KEY (scope_id, ${ident(column)}) REFERENCES ansorito.${ident(target)} (scope_id, ${ident(targetColumn)}) ON DELETE CASCADE;\n`;
sql += `GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA ansorito TO authenticated;
CREATE UNIQUE INDEX notas_er_concepto ON ansorito.config_notas_er (scope_id, concepto_key) WHERE concepto_key IS NOT NULL;
CREATE UNIQUE INDEX notas_er_numero ON ansorito.config_notas_er (scope_id, lower(trim(numero))) WHERE trim(numero) <> '';
CREATE INDEX voucher_periodo ON ansorito.vouchers (scope_id, periodo, fecha);
CREATE INDEX detalle_voucher ON ansorito.voucher_detalles (scope_id, voucher_id);
CREATE INDEX detalle_cuenta ON ansorito.voucher_detalles (scope_id, cuenta);
CREATE INDEX sire_periodo ON ansorito.sire_operaciones (scope_id, periodo, tipo);
`;
const destination = path.join(
  __dirname,
  "../supabase/migrations/202610080001_original_accounting.sql",
);
fs.writeFileSync(destination, sql);
console.log(
  `Generated ${tables.length} accounting tables and company registry.`,
);
